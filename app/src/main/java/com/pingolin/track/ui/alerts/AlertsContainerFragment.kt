package com.pingolin.track.ui.alerts

import android.os.Bundle
import android.view.LayoutInflater
import android.view.View
import android.view.ViewGroup
import androidx.fragment.app.Fragment
import androidx.viewpager2.adapter.FragmentStateAdapter
import com.google.android.material.tabs.TabLayoutMediator
import com.pingolin.track.R
import com.pingolin.track.databinding.FragmentAlertsContainerBinding
import com.pingolin.track.ui.alerts.history.AlertEventsFragment
import dagger.hilt.android.AndroidEntryPoint

@AndroidEntryPoint
class AlertsContainerFragment : Fragment() {

    private var _binding: FragmentAlertsContainerBinding? = null
    private val binding get() = _binding!!

    override fun onCreateView(
        inflater: LayoutInflater,
        container: ViewGroup?,
        savedInstanceState: Bundle?
    ): View {
        _binding = FragmentAlertsContainerBinding.inflate(inflater, container, false)
        return binding.root
    }

    override fun onViewCreated(view: View, savedInstanceState: Bundle?) {
        super.onViewCreated(view, savedInstanceState)

        setupViewPager()
        setupToolbar()
    }

    private fun setupViewPager() {
        val adapter = AlertsPagerAdapter(this)
        binding.viewPager.adapter = adapter

        TabLayoutMediator(binding.tabLayout, binding.viewPager) { tab, position ->
            tab.text = when (position) {
                0 -> getString(R.string.safety_rules_tab_alerts)
                1 -> getString(R.string.safety_rules_tab_history)
                else -> ""
            }
        }.attach()
    }

    private fun setupToolbar() {
        binding.toolbar.setNavigationOnClickListener {
            requireActivity().onBackPressedDispatcher.onBackPressed()
        }
    }

    override fun onDestroyView() {
        super.onDestroyView()
        _binding = null
    }

    private inner class AlertsPagerAdapter(fragment: Fragment) : FragmentStateAdapter(fragment) {
        override fun getItemCount(): Int = 2

        override fun createFragment(position: Int): Fragment {
            return when (position) {
                0 -> AlertsFragment()
                1 -> AlertEventsFragment()
                else -> throw IllegalArgumentException("Invalid position: $position")
            }
        }
    }
}
