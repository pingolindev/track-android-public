package com.pingolin.track.util

/** Coordinates as the app shows them: always with a decimal point, whatever the phone's language ("52,52000, 13,40500" reads as four numbers). */
fun coordinatesText(latitude: Double, longitude: Double): String =
    String.format(java.util.Locale.ROOT, "%.5f, %.5f", latitude, longitude)
