package com.pingolin.track.ui.settings

import androidx.test.core.app.ApplicationProvider
import android.app.Application
import org.junit.Assert.assertTrue
import org.junit.Test
import org.junit.runner.RunWith
import org.robolectric.RobolectricTestRunner
import org.robolectric.annotation.Config

/**
 * The third-party licence notices must actually ship.
 *
 * `assets/open_source_licenses.html` is generated by
 * `./gradlew :app:generateThirdPartyLicenses` and committed. Nothing in a normal
 * build regenerates it, which is the point — but it also means a dependency
 * change can silently leave the notices stale, and deleting the asset would only
 * show up as a blank WebView on a screen nobody opens during development.
 * Attribution is a licence obligation, so it is checked here instead.
 *
 * This reads through the Android asset manager rather than off the filesystem,
 * so it proves the file is packaged for the variant, not merely present in the
 * source tree.
 */
// Robolectric 4.14.1 has no SDK 36 image, so pin 34 as the rest of the suite
// does. A plain Application keeps TrackApplication's startup (Hilt, SDK init)
// out of a test that only needs the asset manager. Note the absence of
// manifest = Config.NONE: without the merged manifest there are no assets to
// read.
@RunWith(RobolectricTestRunner::class)
@Config(sdk = [34], application = android.app.Application::class)
class OpenSourceLicensesAssetTest {

    private fun notices(): String =
        ApplicationProvider.getApplicationContext<Application>()
            .assets
            .open("open_source_licenses.html")
            .bufferedReader()
            .use { it.readText() }

    @Test
    fun `notices asset is packaged and non-trivial`() {
        val html = notices()
        // The generated inventory runs to ~160 components; anything near-empty
        // means the asset was truncated or replaced by a placeholder.
        assertTrue(
            "open_source_licenses.html is only ${html.length} chars",
            html.length > 20_000,
        )
        assertTrue(html.contains("<title>Open source licenses</title>"))
    }

    /**
     * JNA is dual-licensed LGPL-2.1-or-later / Apache-2.0. The app uses it
     * under Apache-2.0, and that election has to be stated rather than left
     * for a reader to guess — leaving it ambiguous is the actual licence
     * risk.
     */
    @Test
    fun `JNA licence election is stated explicitly`() {
        val html = notices()
        assertTrue("JNA missing from notices", html.contains("net.java.dev.jna:jna"))
        assertTrue("JNA dual licence not disclosed", html.contains("LGPL-2.1-or-later"))
        assertTrue(
            "JNA licence election not stated",
            html.contains("Elected: Apache License 2.0"),
        )
    }

    /**
     * Components whose POMs are incomplete or whose licences are easy to lose in
     * a regeneration. SQLCipher in particular publishes a `<license>` element
     * with no name, so it only appears here because
     * app/licenses/manual-licenses.json fills it in.
     */
    @Test
    fun `notable bundled components are attributed`() {
        val html = notices()
        listOf(
            "net.zetetic:sqlcipher-android",
            "org.maplibre.gl:android-sdk",
            "org.mindrot:jbcrypt",
            "org.unifiedpush.android:connector",
            "com.google.firebase:firebase-messaging",
            "com.google.android.gms:play-services-location",
            "com.squareup.okhttp3:okhttp",
        ).forEach {
            assertTrue("$it missing from the licence notices", html.contains(it))
        }
        assertTrue(
            "SQLCipher licence not resolved",
            html.contains("BSD 3-Clause License"),
        )
    }

    /**
     * The Gradle licence plugin reads POM metadata, so it is blind to the Rust
     * crates statically linked into libpingolin_mobile.so — notices built from
     * Gradle alone are materially incomplete. That half comes from
     * app/licenses/native-rust-licenses.json, refreshed by
     * tools/generate-native-licenses.py, and nothing in a Gradle build can
     * regenerate it. If it is dropped, the whole native inventory disappears
     * silently, so pin it here.
     */
    @Test
    fun `native Rust crates linked into the shared library are attributed`() {
        val html = notices()
        assertTrue(
            "Native (Rust) section missing",
            html.contains("Native (Rust) components"),
        )
        assertTrue(
            "the native library is not named",
            html.contains("libpingolin_mobile.so"),
        )
        // Crypto, storage and FFI crates that are compiled into the .so. These
        // are direct dependencies of the mobile SDK, so they should survive
        // any routine dependency bump.
        listOf(
            "ring",
            "rusqlite",
            "libsqlite3-sys",
            "uniffi",
            "x25519-dalek",
            "ed25519-dalek",
            "blake3",
            "argon2",
        ).forEach {
            assertTrue("native crate $it missing from the licence notices", html.contains(it))
        }
    }

    /**
     * rusqlite is built with `bundled`, which compiles the SQLite C amalgamation
     * into the shared library. The crate's MIT licence covers the Rust binding,
     * not that C source, so the notice has to say where the bundled code stands.
     */
    @Test
    fun `bundled SQLite source is accounted for`() {
        val html = notices()
        assertTrue(
            "bundled SQLite provenance not disclosed",
            html.contains("SQLite C amalgamation"),
        )
        assertTrue(
            "SQLite public-domain dedication not cited",
            html.contains("sqlite.org/copyright.html"),
        )
    }
}
